#!/usr/bin/env python3
"""
Turn the FocalTech firmware image the phone runs into C for the loader.

  mkftsfw.py <focaltech_ts_fw_*.bin> <out.h>

The FT8719 has no flash: its application lives in PRAM and is gone the moment the chip is reset,
which every boot does. Android therefore carries the image in /vendor/firmware and its driver sends
it over SPI at probe; the loader has to do the same before it starts XNU, because the kernel comes
up long after the chip has forgotten everything.

The image's download header sits at 0x100: two big-endian lengths that add up to 0xffff, the first
of which -- code_len -- says how much of the file goes to PRAM. The bytes after code_len are DRAM
data, which this chip does not take (upgrade_setting_list[0] has drwr_support = 0), so the header
written here is the PRAM half only.

The generated header is a vendor's firmware and never goes into the repository (.gitignore).
"""
import os
import struct
import sys

APP_INFO = 0x100
PER_LINE = 12


def main(argv):
    if len(argv) != 3:
        raise SystemExit('usage: mkftsfw.py <firmware.bin> <out.h>')
    src, dst = argv[1], argv[2]
    with open(src, 'rb') as f:
        image = f.read()
    if len(image) < APP_INFO + 12:
        raise SystemExit('%s: too short for a firmware image' % src)

    code_len, code_len_n = struct.unpack_from('>HH', image, APP_INFO)
    if (code_len + code_len_n) & 0xffff != 0xffff:
        raise SystemExit('%s: code_len 0x%04x + 0x%04x is not 0xffff' %
                         (src, code_len, code_len_n))
    if code_len > len(image):
        raise SystemExit('%s: code_len 0x%04x is past the end of the file' % (src, code_len))

    code = image[:code_len]
    const_len, = struct.unpack_from('>H', image, APP_INFO + 8)

    with open(dst, 'w') as f:
        f.write('/* Generated by tools/mkftsfw.py from %s. Do not edit. */\n' %
                os.path.basename(src))
        f.write('/* PRAM %u bytes (code_len 0x%04x); the DRAM half (0x%04x) is not used by the '
                'FT8719. */\n' % (code_len, code_len, const_len))
        f.write('#ifndef FTSFW_H\n#define FTSFW_H\n\n#include <stdint.h>\n\n')
        f.write('#define FTS_FW_SIZE %uu\n\n' % code_len)
        f.write('static const uint8_t FTS_FW[FTS_FW_SIZE] = {\n')
        for at in range(0, len(code), PER_LINE):
            row = code[at:at + PER_LINE]
            f.write('\t' + ''.join('0x%02x, ' % b for b in row).rstrip() + '\n')
        f.write('};\n\n#endif /* FTSFW_H */\n')

    print('%s: PRAM %u bytes of %u -> %s' % (src, code_len, len(image), dst))


if __name__ == '__main__':
    main(sys.argv)